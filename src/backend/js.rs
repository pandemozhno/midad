use crate::ast::{BinOp, UnOp};
use crate::sem::*;

pub struct JsBackend { out: String, indent: usize }

impl JsBackend {
    pub fn new() -> Self { Self { out: String::new(), indent: 0 } }

    pub fn emit(mut self, m: &SemModule) -> String {
        self.out.push_str("// generated by midc v0.3 · JS backend\n'use strict';\n\n");
        self.out.push_str(
            "function __qalam_show(s, f) { console.log(String(s)); }\n\n");

        for s in &m.structs { self.emit_class(s, &m.impls); }
        for f in &m.fns { self.emit_fn(f); }
        for r in &m.rules { self.emit_rule(r); }

        if let Some(entry) = &m.entry {
            self.out.push_str(&format!("{}\n", entry));
        } else if m.fns.iter().any(|f| f.sig.name == "main") {
            self.out.push_str("\nmain();\n");
        }
        self.out
    }

    fn emit_class(&mut self, s: &SemStruct, impls: &[SemImpl]) {
        self.out.push_str(&format!("class {} {{\n", s.name));
        self.indent += 1;
        self.push("constructor(init = {}) {");
        self.indent += 1;
        for (n, t, d) in &s.fields {
            let init = match d {
                Some(e) => self.expr(e),
                None => t.js_zero().to_string(),
            };
            self.push(&format!("this.{} = init.{} ?? {};", n, n, init));
        }
        self.push("this._listeners = {};");
        self.indent -= 1;
        self.push("}");
        self.push("_emit(event, ...args) {");
        self.indent += 1;
        self.push("(this._listeners[event] || []).forEach(fn => fn.call(this, this, ...args));");
        self.push("(this.constructor._autoRules || []).forEach(r => { if (r[0] === event) r[1].call(this, this, ...args); });");
        self.indent -= 1;
        self.push("}");
        self.push("on(event, fn) { (this._listeners[event] ||= []).push(fn); return this; }");
        self.indent -= 1;
        self.push("}\n");
        self.out.push_str(&format!("{}._autoRules = [];\n\n", s.name));

        for imp in impls {
            if let Ty::Named(n) = &imp.for_type {
                if n == &s.name {
                    for method in &imp.methods {
                        self.emit_method(method);
                    }
                }
            }
        }
    }

    fn emit_method(&mut self, f: &SemFn) {
        let params = f.sig.params.iter().skip(1)
            .map(|(n, _)| n.clone()).collect::<Vec<_>>().join(", ");
        let pad = "  ".repeat(self.indent);
        self.out.push_str(&format!("{}{}({}) {{\n", pad, f.sig.name, params));
        self.indent += 1;
        for s in &f.body { self.stmt(s); }
        self.indent -= 1;
        let pad = "  ".repeat(self.indent);
        self.out.push_str(&format!("{}}}\n", pad));
    }

    fn emit_fn(&mut self, f: &SemFn) {
        let params = f.sig.params.iter()
            .map(|(n, _)| n.clone()).collect::<Vec<_>>().join(", ");
        let pad = "  ".repeat(self.indent);
        self.out.push_str(&format!("{}function {}({}) {{\n", pad, f.sig.name, params));
        self.indent += 1;
        for s in &f.body { self.stmt(s); }
        self.indent -= 1;
        self.out.push_str("}\n\n");
    }

    fn emit_rule(&mut self, r: &SemRule) {
        self.out.push_str(&format!(
            "// rule: when {}.{}\nfunction __rule_{}_{}(self, ...args) {{\n",
            r.when_type, r.when_event, r.when_type, r.when_event));
        self.indent += 1;
        for s in &r.body { self.stmt(s); }
        self.indent -= 1;
        self.out.push_str("}\n");
        self.out.push_str(&format!(
            "{}._autoRules.push(['{}', __rule_{}_{}]);\n\n",
            r.when_type, r.when_event, r.when_type, r.when_event));
    }

    fn push(&mut self, s: &str) {
        let pad = "  ".repeat(self.indent);
        self.out.push_str(&pad);
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn stmt(&mut self, s: &SemStmt) {
        match s {
            SemStmt::Let(n, _, v) => {
                let e = self.expr(v);
                self.push(&format!("let {} = {};", n, e));
            }
            SemStmt::Assign(t, v) => {
                let t_s = self.expr(t);
                let v_s = self.expr(v);
                self.push(&format!("{} = {};", t_s, v_s));
            }
            SemStmt::Return(Some(e)) => self.push(&format!("return {};", self.expr(e))),
            SemStmt::Return(None) => self.push("return;"),
            SemStmt::If(c, t, e) => {
                self.push(&format!("if ({}) {{", self.expr(c)));
                self.indent += 1;
                for s in t { self.stmt(s); }
                self.indent -= 1;
                if !e.is_empty() {
                    self.push("} else {");
                    self.indent += 1;
                    for s in e { self.stmt(s); }
                    self.indent -= 1;
                }
                self.push("}");
            }
            SemStmt::While(c, b) => {
                self.push(&format!("while ({}) {{", self.expr(c)));
                self.indent += 1;
                for s in b { self.stmt(s); }
                self.indent -= 1;
                self.push("}");
            }
            SemStmt::ExprStmt(e) => self.push(&format!("{};", self.expr(e))),
            SemStmt::Emit(ev) => self.push(&format!("self._emit('{}');", ev)),
            SemStmt::Panic(msg) => {
                let esc = msg.replace('"', "\\\"");
                self.push(&format!("throw new Error(\"{}\");", esc));
            }
            SemStmt::Show(e, _) => {
                self.push(&format!("__qalam_show({});", self.expr(e)));
            }
            SemStmt::Unsafe(b) => for s in b { self.stmt(s); },
            _ => {}
        }
    }

    fn expr(&self, e: &SemExpr) -> String {
        match e {
            SemExpr::Unit => "undefined".into(),
            SemExpr::Bool(b) => format!("{}", b),
            SemExpr::Int(n, _) => format!("{}", n),
            SemExpr::Float(f, _) => format!("{}", f),
            SemExpr::Str(s) => {
                let esc = s.replace('\\', "\\\\").replace('"', "\\\"")
                            .replace('\n', "\\n").replace('\t', "\\t");
                format!("\"{}\"", esc)
            }
            SemExpr::Var(n) => n.clone(),
            SemExpr::Field(b, f) => format!("{}.{}", self.expr(b), f),
            SemExpr::Call(n, a) => format!("{}({})", n,
                a.iter().map(|x| self.expr(x)).collect::<Vec<_>>().join(", ")),
            SemExpr::MethodCall(o, m, a) => format!("{}.{}({})",
                self.expr(o), m,
                a.iter().map(|x| self.expr(x)).collect::<Vec<_>>().join(", ")),
            SemExpr::Bin(op, a, b, _) => format!("({} {} {})",
                self.expr(a), binop_js(*op), self.expr(b)),
            SemExpr::Un(op, a, _) => format!("({}{})", unop_str(*op), self.expr(a)),
            SemExpr::Cast(a, _) => self.expr(a),
            SemExpr::StructLit(n, f) => format!("new {}({{ {} }})", n,
                f.iter().map(|(k, v)| format!("{}: {}", k, self.expr(v)))
                 .collect::<Vec<_>>().join(", ")),
            _ => "undefined".into(),
        }
    }
}

fn binop_js(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "+", BinOp::Sub => "-", BinOp::Mul => "*",
        BinOp::Div => "/", BinOp::Mod => "%",
        BinOp::Eq => "===", BinOp::Ne => "!==",
        BinOp::Lt => "<", BinOp::Gt => ">",
        BinOp::Le => "<=", BinOp::Ge => ">=",
        BinOp::And => "&&", BinOp::Or => "||",
        BinOp::BitAnd => "&", BinOp::BitOr => "|",
        BinOp::BitXor => "^", BinOp::Shl => "<<", BinOp::Shr => ">>",
    }
}

fn unop_str(op: UnOp) -> &'static str {
    match op { UnOp::Not => "!", UnOp::BitNot => "~", UnOp::Neg => "-" }
}