use std::collections::HashMap;
use crate::ast::{BinOp, Profile, UnOp};
use crate::sem::*;

pub struct CBackend {
    out: String,
    indent: usize,
    counter: u32,
    method_types: HashMap<String, String>,
    method_ret_types: HashMap<String, Ty>,
}

impl CBackend {
    pub fn new() -> Self {
        Self {
            out: String::new(),
            indent: 0,
            counter: 0,
            method_types: HashMap::new(),
            method_ret_types: HashMap::new(),
        }
    }

    pub fn emit(mut self, m: &SemModule) -> String {
        // сначала регистрируем методы — нужно для MethodCall и Show
        for imp in &m.impls {
            if let Ty::Named(n) = &imp.for_type {
                for f in &imp.methods {
                    self.method_types.insert(f.sig.name.clone(), n.clone());
                    self.method_ret_types.insert(f.sig.name.clone(), f.sig.ret.clone());
                }
            }
        }

        self.prelude(m);
        for s in &m.structs { self.emit_struct(s); }
        for (name, vs) in &m.enums { self.emit_enum(name, vs); }
        for p in &m.protocols { self.emit_protocol(p); }
        for e in &m.externs { self.emit_extern(e); }
        for s in &m.statics { self.emit_static(s); }
        for imp in &m.impls { self.emit_impl(imp); }
        for f in &m.fns { self.emit_fn(f, None); }
        for r in &m.rules { self.emit_rule(r); }

        // entry — только если такой функции ещё нет
        if let Some(entry) = &m.entry {
            let already_defined = m.fns.iter().any(|f| &f.sig.name == entry);
            if !already_defined {
                self.out.push_str(&format!("void _start(void) {{\n    {}();\n    while (1) {{ __asm__ volatile(\"hlt\"); }}\n}}\n", entry));
            }
        }
        self.out
    }

    fn prelude(&mut self, m: &SemModule) {
        self.out.push_str("/* generated by midc v0.3 · C backend */\n");
        self.out.push_str("#include <stdint.h>\n#include <stdbool.h>\n");
        if m.profile == Profile::Kernel {
            self.out.push_str("#define NULL ((void*)0)\n");
            self.out.push_str("void mid_panic(const char* msg) { (void)msg; __builtin_trap(); }\n\n");
        } else {
            self.out.push_str("#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\n");
            self.out.push_str(
                "static void __qalam_show_str(const char* s) {\n\
                 \x20   fputs(s, stdout);\n\
                 \x20   fputc('\\n', stdout);\n\
                 }\n\n");
            self.out.push_str(
                "static void __qalam_show_int(long long v) {\n\
                 \x20   printf(\"%lld\\n\", v);\n\
                 }\n\n");
            self.out.push_str(
                "static void __qalam_show_bool(int v) {\n\
                 \x20   fputs(v ? \"true\\n\" : \"false\\n\", stdout);\n\
                 }\n\n");
            self.out.push_str("void mid_panic(const char* msg) { fputs(msg, stderr); __builtin_trap(); }\n\n");
        }
    }

    fn push(&mut self, s: &str) {
        for _ in 0..self.indent { self.out.push_str("    "); }
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn emit_struct(&mut self, s: &SemStruct) {
        self.out.push_str(&format!("typedef struct {} {{\n", s.name));
        for (n, t, _) in &s.fields {
            self.out.push_str(&format!("    {} {};\n", t.c_name(), n));
        }
        self.out.push_str(&format!("}} {};\n\n", s.name));
    }

    fn emit_enum(&mut self, name: &str, variants: &[String]) {
        self.out.push_str(&format!("typedef enum {} {{\n", name));
        for v in variants {
            self.out.push_str(&format!("    {}_{},\n", name, v));
        }
        self.out.push_str(&format!("}} {};\n\n", name));
    }

    fn emit_protocol(&mut self, p: &SemProtocol) {
        self.out.push_str(&format!("typedef struct {}_vt {{\n", p.name));
        for s in &p.methods {
            let params = if s.params.is_empty() {
                "void".to_string()
            } else {
                s.params.iter()
                    .map(|(n, t)| {
                        if n == "self" { "void* self".to_string() }
                        else { format!("{} {}", t.c_name(), n) }
                    })
                    .collect::<Vec<_>>().join(", ")
            };
            self.out.push_str(&format!("    {} (*{})({});\n", s.ret.c_name(), s.name, params));
        }
        self.out.push_str(&format!("}} {}_vt;\n\n", p.name));
    }

    fn emit_extern(&mut self, e: &SemExtern) {
        if e.abi != "C" { return; }
        for s in &e.sigs {
            let params = if s.params.is_empty() { "void".to_string() }
                else { s.params.iter()
                    .map(|(n, t)| format!("{} {}", t.c_name(), n))
                    .collect::<Vec<_>>().join(", ") };
            self.out.push_str(&format!("{} {}({});\n", s.ret.c_name(), s.name, params));
        }
        self.out.push('\n');
    }

    fn emit_static(&mut self, s: &SemStatic) {
        let qual = if s.mutable { "" } else { "const " };
        let init = match &s.init {
            Some(e) => format!(" = {}", self.expr(e)),
            None => String::new(),
        };
        self.out.push_str(&format!("static {}{} {}{};\n\n",
            qual, s.ty.c_name(), s.name, init));
    }

    fn emit_impl(&mut self, imp: &SemImpl) {
        let type_name = match &imp.for_type {
            Ty::Named(n) => n.clone(),
            _ => return,
        };
        for m in &imp.methods {
            self.emit_fn(m, Some(&type_name));
        }
        // vtable-init отключён — не используется и ломает `Self`
        let _ = &imp.protocol;
    }

    fn emit_fn(&mut self, f: &SemFn, self_type: Option<&str>) {
        let name = if let Some(st) = self_type {
            format!("{}_{}", st, f.sig.name)
        } else {
            f.sig.name.clone()
        };
        let params = if f.sig.params.is_empty() { "void".to_string() }
            else { f.sig.params.iter()
                .map(|(n, t)| {
                    if n == "self" { format!("{}* self", self_type.unwrap_or("void")) }
                    else { format!("{} {}", t.c_name(), n) }
                })
                .collect::<Vec<_>>().join(", ") };
        self.out.push_str(&format!("{} {}({}) {{\n", f.sig.ret.c_name(), name, params));
        self.indent += 1;
        for s in &f.body { self.stmt(s); }
        self.indent -= 1;
        self.out.push_str("}\n\n");
    }

    fn emit_rule(&mut self, r: &SemRule) {
        let name = format!("{}__{}", r.when_type, r.when_event);
        let params = std::iter::once(format!("{}* self", r.when_type))
            .chain(r.params.iter().map(|(n, t)| format!("{} {}", t.c_name(), n)))
            .collect::<Vec<_>>().join(", ");
        self.out.push_str(&format!("/* rule: when {}.{} */\n", r.when_type, r.when_event));
        self.out.push_str(&format!("void {}({}) {{\n", name, params));
        self.indent += 1;
        for s in &r.body { self.stmt(s); }
        self.indent -= 1;
        self.out.push_str("}\n\n");
    }

    fn stmt(&mut self, s: &SemStmt) {
        match s {
            SemStmt::Let(n, t, v) => {
                let v_s = self.expr(v);
                self.push(&format!("{} {} = {};", t.c_name(), n, v_s));
            }
            SemStmt::Assign(t, v) => {
                let t_s = self.expr(t);
                let v_s = self.expr(v);
                self.push(&format!("{} = {};", t_s, v_s));
            }
            SemStmt::Return(Some(e)) => {
                let v = self.expr(e);
                self.push(&format!("return {};", v));
            }
            SemStmt::Return(None) => self.push("return;"),
            SemStmt::If(c, t, e) => {
                let c_s = self.expr(c);
                self.push(&format!("if ({}) {{", c_s));
                self.indent += 1;
                for s in t { self.stmt(s); }
                self.indent -= 1;
                if !e.is_empty() {
                    self.push("} else {");
                    self.indent += 1;
                    for s in e { self.stmt(s); }
                    self.indent -= 1;
                }
                self.push("}");
            }
            SemStmt::While(c, b) => {
                let c_s = self.expr(c);
                self.push(&format!("while ({}) {{", c_s));
                self.indent += 1;
                for s in b { self.stmt(s); }
                self.indent -= 1;
                self.push("}");
            }
            SemStmt::ForEach(v, i, b) => {
                self.counter += 1;
                let ii = format!("__i{}", self.counter);
                let i_s = self.expr(i);
                self.push(&format!("for (int {} = 0; {} < ({}); {}++) {{", ii, ii, i_s, ii));
                self.indent += 1;
                self.push(&format!("int {} = ({});", v, ii));
                for s in b { self.stmt(s); }
                self.indent -= 1;
                self.push("}");
            }
            SemStmt::ExprStmt(e) => {
                let s = self.expr(e);
                self.push(&format!("{};", s));
            }
            SemStmt::Unsafe(b) => {
                self.push("{");
                self.indent += 1;
                for s in b { self.stmt(s); }
                self.indent -= 1;
                self.push("}");
            }
            SemStmt::Assembly(ops) => {
                for op in ops { self.asm(op); }
            }
            SemStmt::Panic(msg) => {
                let esc = msg.replace('"', "\\\"");
                self.push(&format!("mid_panic(\"{}\");", esc));
            }
            SemStmt::Emit(_) => {
                // no-op в C; правило вызывается явно
            }
            SemStmt::Show(e, _f) => {
                let s = self.expr(e);
                let ty = self.expr_type(e);
                match ty {
                    Ty::Str => self.push(&format!("__qalam_show_str((const char*)({}));", s)),
                    Ty::Bool => self.push(&format!("__qalam_show_bool((int)({}));", s)),
                    _ => self.push(&format!("__qalam_show_int((long long)({}));", s)),
                }
            }
        }
    }

    fn asm(&mut self, op: &SemAsm) {
        match op {
            SemAsm::Output(p, v) => {
                let p_s = self.expr(p);
                let v_s = self.expr(v);
                self.push(&format!(
                    "{{ uint16_t __p = {}; uint8_t __v = {}; __asm__ volatile(\"outb %0, %1\" :: \"a\"(__v), \"Nd\"(__p)); }}",
                    p_s, v_s));
            }
            SemAsm::Input(p) => {
                let p_s = self.expr(p);
                self.push(&format!(
                    "{{ uint16_t __p = {}; uint8_t __r; __asm__ volatile(\"inb %1, %0\" : \"=a\"(__r) : \"Nd\"(__p)); (void)__r; }}",
                    p_s));
            }
            SemAsm::Interrupt(n) => {
                let n_s = self.expr(n);
                self.push(&format!("__asm__ volatile(\"int ${}\");", n_s));
            }
            SemAsm::Halt => self.push("__asm__ volatile(\"hlt\");"),
            SemAsm::NoOperation => self.push("__asm__ volatile(\"nop\");"),
        }
    }

    fn expr(&self, e: &SemExpr) -> String {
        match e {
            SemExpr::Unit => "0".into(),
            SemExpr::Bool(b) => if *b { "true".into() } else { "false".into() },
            SemExpr::Int(n, _) => format!("0x{:X}", n),
            SemExpr::Float(f, _) => format!("{}", f),
            SemExpr::Str(s) => {
                let esc = s.replace('\\', "\\\\").replace('"', "\\\"")
                            .replace('\n', "\\n").replace('\t', "\\t");
                format!("(uint8_t*)\"{}\"", esc)
            }
            SemExpr::Var(n) => n.clone(),
            SemExpr::Field(b, f) => {
                let base = self.expr(b);
                if base == "self" { format!("self->{}", f) } else { format!("({}).{}", base, f) }
            }
            SemExpr::Call(n, a) => {
                let args = a.iter().map(|x| self.expr(x)).collect::<Vec<_>>().join(", ");
                format!("{}({})", n, args)
            }
            SemExpr::MethodCall(o, m, a) => {
                let ty = self.method_types.get(m).cloned().unwrap_or_default();
                if ty.is_empty() {
                    return format!("/* unknown method {} */ 0", m);
                }
                let obj = self.expr(o);
                let args = a.iter().map(|x| self.expr(x)).collect::<Vec<_>>().join(", ");
                if obj == "self" {
                    let full = if args.is_empty() { obj } else { format!("{}, {}", obj, args) };
                    format!("{}_{}({})", ty, m, full)
                } else {
                    let full = if args.is_empty() { format!("&{}", obj) } else { format!("&{}, {}", obj, args) };
                    format!("{}_{}({})", ty, m, full)
                }
            }
            SemExpr::Bin(op, a, b, _) => {
                let a_s = self.expr(a);
                let b_s = self.expr(b);
                format!("({} {} {})", a_s, binop_str(*op), b_s)
            }
            SemExpr::Un(op, a, _) => {
                format!("({}{})", unop_str(*op), self.expr(a))
            }
            SemExpr::Cast(a, t) => format!("(({})({}))", t.c_name(), self.expr(a)),
            SemExpr::Deref(a) => format!("(*{})", self.expr(a)),
            SemExpr::AddrOf(a) => format!("(&{})", self.expr(a)),
            SemExpr::StructLit(n, f) => {
                let fi = f.iter().map(|(k, v)| format!(".{} = {}", k, self.expr(v)))
                    .collect::<Vec<_>>().join(", ");
                format!("({}){{ {} }}", n, fi)
            }
            SemExpr::AsmInput(p) => format!(
                "({{ uint16_t __p = {}; uint8_t __r; __asm__ volatile(\"inb %1, %0\" : \"=a\"(__r) : \"Nd\"(__p)); __r; }})",
                self.expr(p)),
        }
    }

    fn expr_type(&self, e: &SemExpr) -> Ty {
        match e {
            SemExpr::Str(_) => Ty::Str,
            SemExpr::Bool(_) => Ty::Bool,
            SemExpr::Int(_, t) => t.clone(),
            SemExpr::Float(_, t) => t.clone(),
            SemExpr::Bin(_, _, _, t) => t.clone(),
            SemExpr::Un(_, _, t) => t.clone(),
            SemExpr::Cast(_, t) => t.clone(),
            SemExpr::MethodCall(_, m, _) => self.method_ret_types.get(m).cloned().unwrap_or(Ty::I32),
            SemExpr::Field(_, _) => Ty::I32,
            SemExpr::Var(_) => Ty::I32,
            _ => Ty::I32,
        }
    }
}

fn binop_str(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "+", BinOp::Sub => "-", BinOp::Mul => "*",
        BinOp::Div => "/", BinOp::Mod => "%",
        BinOp::Eq => "==", BinOp::Ne => "!=",
        BinOp::Lt => "<", BinOp::Gt => ">",
        BinOp::Le => "<=", BinOp::Ge => ">=",
        BinOp::And => "&&", BinOp::Or => "||",
        BinOp::BitAnd => "&", BinOp::BitOr => "|",
        BinOp::BitXor => "^", BinOp::Shl => "<<", BinOp::Shr => ">>",
    }
}

fn unop_str(op: UnOp) -> &'static str {
    match op {
        UnOp::Not => "!", UnOp::BitNot => "~", UnOp::Neg => "-",
    }
}